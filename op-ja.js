// The number of a step in the unit its handler uses (technique-opcodes.json meanings; combat-code.md 2.5 for the
// critical term): x = multiplies (×v), pct = v is already a percent, frac = a fraction (0.1 = 10 %), plus = adds v.
// Steps not listed keep their raw number.
const X = [64, 85, 91, 149, 157, 158, 195, 213, 219];
const PCT = [69, 108, 109, 113, 122, 123, 249, 254, 255, 273, 276, 284];
const FRAC = [112, 155, 217, 247, 261, 279];
const PLUS = [142, 163, 167, 188, 196, 235, 245, 248, 259];
const n2 = (v) => (Math.round(v * 1000) / 1000).toString();
const sign = (v) => (v > 0 ? '+' : v < 0 ? '−' : '') + n2(Math.abs(v));
export function stepValue(op, p, v) {
  if (X.includes(op)) return `×${n2(v)}`;
  if (PCT.includes(op)) return `${sign(v)}%`;
  if (FRAC.includes(op)) return `${sign(v * 100)}%`;
  if (PLUS.includes(op)) return sign(v);
  if (op === 92) return `中断されにくさ ${sign(v * 100)}%`;          // +0x5bc = v x 100, added to the keep roll
  if (op === 232) return `${sign(v * 100)}%`;                          // damage taken x (1 + value)
  if (op === 275) return `${sign(v * 100)}%`;                          // element boost x (1 + value)
  if (op === 216) return `反射 ${n2(v)}%・確率 ${n2(p)}%`;              // value = reflect %, param = chance %
  if (op === 2 || op === 82) return v < 0 ? `回復 ${n2(-v)}` : `ダメージ ${n2(v)}`;     // A > 0 damage, A < 0 heal
  if (op === 5 || op === 170) return v < 0 ? `回復 ${n2(-v)}` : `減少 ${n2(v)}`;        // MP -= A (negative restores)
  if (op === 180 || op === 12 || op === 11) return v < 0 ? `回復 ${n2(-v)}` : `ダメージ ${n2(v)}`;   // regen when negative
  if (op === 1 || op === 171) return v > 0 ? `回復 ${n2(v)}` : `減少 ${n2(-v)}`;        // ST += A
  if (op === 13) return `${['', 'HP', 'MP', 'ST'][p] || ''} ${v > 0 ? '回復' : '減少'} ${n2(Math.abs(v))}`;
  return v ? n2(v) : '';
}
